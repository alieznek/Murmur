class LanguageCombo(ThemedComboBox):
    def setCurrentText(self, text):
        index = self.findData(text)
        if index >= 0:
            self.setCurrentIndex(index)
        else:
            super().setCurrentText(text)

    def showPopup(self):  # noqa: N802
        # A separate popup keeps the compact selector readable with long names.
        from screen_translator.ui.design_tokens import theme_for
        if getattr(self, "language_popup", None):
            self.language_popup.close()
            self.language_popup.deleteLater()
        tokens = theme_for(getattr(getattr(self.window(), "surface", None), "theme", "light"))
        self.language_popup = QFrame(self, Qt.WindowType.Popup | Qt.WindowType.FramelessWindowHint)
        popup = self.language_popup
        popup.setObjectName("languagePicker")
        popup.setStyleSheet(f"""
            QFrame#languagePicker {{ background: {tokens.panel}; border: 1px solid {tokens.control_border}; border-radius: 8px; }}
            QLineEdit {{ background: {tokens.soft}; color: {tokens.text}; border: 0; padding: 8px; border-radius: 5px; }}
            QListWidget {{ background: {tokens.panel}; color: {tokens.text}; border: 0; outline: 0; }}
            QListWidget::item {{ min-height: 20px; padding: 6px 8px; border: 0; border-radius: 4px; }}
            QListWidget::item:selected {{ background: {tokens.soft}; color: {tokens.accent}; }}
        """)
        layout = QVBoxLayout(popup)
        layout.setContentsMargins(8, 8, 8, 8)
        search = QLineEdit()
        search.setPlaceholderText("搜索语种 / English / code")
        search.setAccessibleName("搜索语种")
        rows = QListWidget()
        rows.setAccessibleName("可选语种")
        layout.addWidget(search)
        layout.addWidget(rows)
        by_code = {language.code: language for language in LANGUAGES}

        def populate(query=""):
            rows.clear()
            for index in range(self.count()):
                code = language_code(self.itemData(index))
                language = by_code.get(code)
                english = language.english if language else "Auto detect"
                label = f"{self.itemText(index)}  ·  {code}"
                if query.strip().casefold() not in f"{label} {english}".casefold():
                    continue
                item = QListWidgetItem(label)
                item.setData(Qt.ItemDataRole.UserRole, index)
                item.setToolTip(english)
                rows.addItem(item)
                if index == self.currentIndex():
                    rows.setCurrentItem(item)
            if rows.currentRow() < 0 and rows.count():
                rows.setCurrentRow(0)
            if not rows.count():
                empty = QListWidgetItem("没有匹配的语种")
                empty.setFlags(Qt.ItemFlag.NoItemFlags)
                rows.addItem(empty)

        def select(item):
            if item and item.data(Qt.ItemDataRole.UserRole) is not None:
                self.setCurrentIndex(item.data(Qt.ItemDataRole.UserRole))
                popup.close()
                self.setFocus()

        search.textChanged.connect(populate)
        search.returnPressed.connect(lambda: select(rows.currentItem()))
        rows.itemClicked.connect(select)
        rows.itemActivated.connect(select)
        populate()
        popup.resize(286, min(366, 80 + self.count() * 40))
        position = self.mapToGlobal(QPoint(0, self.height()))
        area = self.screen().availableGeometry()
        x = max(area.left(), min(position.x(), area.right() - popup.width() + 1))
        y = position.y() if position.y() + popup.height() <= area.bottom() else self.mapToGlobal(QPoint(0, 0)).y() - popup.height()
        popup.move(x, max(area.top(), y))
        popup.show()
        search.setFocus()

    def hidePopup(self):  # noqa: N802
        if getattr(self, "language_popup", None):
            self.language_popup.close()
        super().hidePopup()


